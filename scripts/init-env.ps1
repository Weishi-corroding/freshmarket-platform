# Create the Docker configuration .env.docker with random secrets; refuses to overwrite an existing file.
# Usage: .\scripts\init-env.ps1   then .\scripts\deploy.ps1
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$envPath = Join-Path $projectRoot '.env.docker'
if (Test-Path -LiteralPath $envPath) { throw '.env.docker already exists; keep the current secrets and edit it manually if necessary.' }
function New-Secret { $bytes = New-Object byte[] 24; $generator = [System.Security.Cryptography.RandomNumberGenerator]::Create(); try { $generator.GetBytes($bytes) } finally { $generator.Dispose() }; return [BitConverter]::ToString($bytes).Replace('-','').ToLowerInvariant() }
$configuration = @(
  '# FreshMarket Docker configuration. Generated by scripts/init-env.ps1; keep this file private.'
  'JWT_SECRET=' + (New-Secret)
  'DB_PASSWORD=' + (New-Secret)
  'MQ_PASSWORD=' + (New-Secret)
  'GRAFANA_PASSWORD=' + (New-Secret)
  'DEMO_PASSWORD=FreshDemo' + (New-Secret).Substring(0,16)
  # A unique project name keeps volumes of different checkouts apart; never change it for an existing deployment.
  'COMPOSE_PROJECT_NAME=freshmarket-' + (New-Secret).Substring(0,8)
  'CORS_ORIGIN=http://localhost:8080'
  'WEB_BIND=127.0.0.1'
  # Set both to false for a public deployment: no demo accounts, no demo login hints in the storefront.
  'SEED_DEMO=true'
  'VITE_DEMO=true'
  'APP_VERSION=local'
)
[System.IO.File]::WriteAllLines($envPath,$configuration,(New-Object System.Text.UTF8Encoding($false)))
Write-Output 'Created .env.docker with generated secrets. Next: .\scripts\deploy.ps1'
