#!/usr/bin/env sh
# 生成 Docker 部署配置 .env.docker：所有密码与密钥随机生成，已存在时拒绝覆盖。
# 用法：sh scripts/init-env.sh   之后执行 sh scripts/deploy.sh
set -eu
cd "$(dirname "$0")/.."
if [ -f .env.docker ]; then echo '.env.docker already exists; keep the current secrets and edit it manually if necessary.' >&2; exit 1; fi
umask 077
secret() { od -vAn -N24 -tx1 /dev/urandom | tr -d ' \n'; }
{
  echo '# FreshMarket Docker configuration. Generated by scripts/init-env.sh; keep this file private.'
  echo "JWT_SECRET=$(secret)"
  echo "DB_PASSWORD=$(secret)"
  echo "MQ_PASSWORD=$(secret)"
  echo "GRAFANA_PASSWORD=$(secret)"
  echo "DEMO_PASSWORD=FreshDemo$(secret | cut -c1-16)"
  # 每份部署使用独立的 Compose 项目名，避免同机多份检出共用数据卷；已有部署不要修改
  echo "COMPOSE_PROJECT_NAME=freshmarket-$(secret | cut -c1-8)"
  echo 'CORS_ORIGIN=http://localhost:8080'
  echo 'WEB_BIND=127.0.0.1'
  # 对外部署时改为 false：不写入演示账号，前端不显示演示入口
  echo 'SEED_DEMO=true'
  echo 'VITE_DEMO=true'
  echo 'APP_VERSION=local'
} > .env.docker
echo 'Created .env.docker with generated secrets. Next: sh scripts/deploy.sh'
